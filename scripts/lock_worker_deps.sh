#!/usr/bin/env bash
# Regenerate hash-pinned lock files for docker/Dockerfile.worker.python-base.experiment.
# Requires uv. Target: CPython 3.11, linux x86_64 (manylinux_2_28; bookworm glibc 2.36).
set -euo pipefail
cd "$(dirname "$0")/../docker/locks"
CUTOFF="${CUTOFF:-2026-10-15T00:00:00Z}"
O=(--python-version 3.11 --python-platform x86_64-manylinux_2_28 --generate-hashes --no-header --exclude-newer "$CUTOFF" -q)
IDX=(--index-url https://download.pytorch.org/whl/cu126 --extra-index-url https://pypi.org/simple --index-strategy unsafe-best-match)
T=$(mktemp -d)
uv pip compile worker-torch.in "${O[@]}" "${IDX[@]}" -o "$T/torch.lock"
uv pip compile worker-torch.in worker-runtime.in "${O[@]}" "${IDX[@]}" -o "$T/all.lock"
uv pip compile worker-nodeps.in "${O[@]}" --no-deps -o "$T/nodeps.lock"
uv pip compile worker-bootstrap.in "${O[@]}" --no-deps -o "$T/boot.lock"
python3 - "$T" <<'PY'
import re, sys
T = sys.argv[1]
def blocks(p):
    out, cur = {}, None
    for l in open(p):
        if re.match(r'^[a-z0-9]', l): cur = l.split('==')[0]; out[cur] = [l]
        elif cur and l.startswith('    --hash'): out[cur].append(l)
    return out
a = blocks(f'{T}/all.lock'); t = set(blocks(f'{T}/torch.lock'))
hdr = "# Generated by scripts/lock_worker_deps.sh -- do not edit by hand.\n"
w = lambda n, b, ks: open(n, 'w').write(hdr + ''.join(''.join(b[k]) for k in ks))
# torch layer uses versions from the full resolution (e.g. numpy<2) so both layers are consistent.
w('worker-torch-cu126.lock', a, sorted(t))
w('worker-runtime.lock', a, sorted(set(a) - t))
for n, f in [('worker-bootstrap.lock', 'boot.lock'), ('worker-nodeps.lock', 'nodeps.lock')]:
    b = blocks(f'{T}/{f}'); w(n, b, list(b))
PY
rm -rf "$T"
